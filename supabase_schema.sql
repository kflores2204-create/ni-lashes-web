-- 1. Crear tabla de Ítems (Servicios y Productos)
CREATE TABLE IF NOT EXISTS public.items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type TEXT NOT NULL CHECK (type IN ('service', 'product')),
    name TEXT NOT NULL,
    description TEXT,
    price NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    igv_percent NUMERIC(5,2) NOT NULL DEFAULT 18.00,
    stock INTEGER DEFAULT NULL,
    image_url TEXT,
    category TEXT DEFAULT 'General',
    duration_minutes INTEGER DEFAULT 90,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Crear tabla de Citas y Reservas
CREATE TABLE IF NOT EXISTS public.appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT REFERENCES public.items(id) ON DELETE RESTRICT,
    client_name TEXT NOT NULL,
    client_phone TEXT NOT NULL,
    client_email TEXT,
    appointment_date TEXT NOT NULL,
    appointment_time TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed', 'cancelled', 'completed')),
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Habilitar Seguridad a Nivel de Fila (RLS)
ALTER TABLE public.items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.appointments ENABLE ROW LEVEL SECURITY;

-- Políticas de lectura y escritura pública para la web
CREATE POLICY "Permitir lectura publica de items" ON public.items
    FOR SELECT USING (true);

CREATE POLICY "Permitir insertar/modificar items" ON public.items
    FOR ALL USING (true);

CREATE POLICY "Permitir crear reservas publicamente" ON public.appointments
    FOR INSERT WITH CHECK (true);

CREATE POLICY "Permitir lectura y actualizacion de citas" ON public.appointments
    FOR ALL USING (true);

